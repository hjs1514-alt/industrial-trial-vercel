/* ── 역할별 사용자 지시문 ── */
export function buildPrompt(role, ctx) {
  switch (role) {
    /* 토론 한 차례. 앞선 대화는 history 로 따로 전달됩니다. */
    case "ai_rebut":
      return ctx.question;

    case "ai_cross": {
      const w = WITNESS_NAME[ctx.witnessId];
      return `상대측이 증인 「${w}」을(를) 불러 물었습니다. 오간 내용입니다.

${ctx.witnessLog}

이제 같은 증인에게 당신이 한 가지 묻습니다.
· 증인을 무너뜨리는 것이 목적이 아닙니다. 이 증언 하나로 산업혁명 전체를 판단할 수 있는지 의심하게 만드는 것이 목적입니다.
· 반드시 방금 증인이 실제로 한 말에서 출발합니다.
· 증인의 처지에서 대답할 수 있는 범위로만 묻습니다. 전국 통계처럼 증인이 알 수 없는 것을 묻지 않습니다.
· 증인에게 예의를 지키되 물러서지 않습니다.
· 질문은 하나. 한두 문장으로 질문만 말합니다. 다른 말을 붙이지 않습니다.`;
    }

    case "witness":
    case "defendant":
      return ctx.question;

    case "ai_closing":
      return `재판이 끝나갑니다. 오늘 법정에서 오간 기록 전부입니다.

${ctx.record}

이제 당신의 마지막 진술을 하십시오.
· 오늘 실제로 오간 이야기만 다룹니다. 새 논점을 잔뜩 끌어오지 않습니다.
· 증인이 나왔다면 증인이 실제로 한 말을 인용하며 정리합니다.
· 상대의 말 중 당신을 정말 곤란하게 만든 부분이 있었다면 솔직히 인정합니다.
· 그러나 여전히 남는 문제를 분명히 짚습니다.
· 마지막 한 문장은 판단을 앞둔 사람이 반드시 통과해야 할 질문이 되게 만듭니다.
· 300~400자. 문장을 짧게 끊습니다. 여덟 문장을 넘기지 않습니다.`;

    default:
      return "";
  }
}

export const ROLES = ["ai_rebut", "ai_cross", "ai_closing", "witness", "defendant"];
